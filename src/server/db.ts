  // QR Session Operations
  public async getQRSessions(): Promise<QRSession[]> {
    const now = new Date();
    const sessions = await MongoAttendanceSession.find().lean();
    const updatedSessions = [];

    for (const s of sessions) {
      let doc = s;
      let updated = false;

      // 1. Check expiration
      if (s.status === 'Active' && new Date(s.expiryTime) < now) {
        s.status = 'Expired';
        updated = true;
      }
      
      // 2. Dynamic token rotation after 30 seconds
      if (s.status === 'Active') {
        const lastRegen = s.lastRegeneratedAt ? new Date(s.lastRegeneratedAt).getTime() : 0;
        const diffMs = now.getTime() - lastRegen;
        if (diffMs > 30 * 1000) {
          s.qrToken = 'TOKEN_' + Math.random().toString(36).substring(2, 9).toUpperCase() + '_' + Math.floor(now.getTime() / 1000);
          s.lastRegeneratedAt = now.toISOString();
          updated = true;
        }
      }

      if (updated) {
        const updatedDoc = await MongoAttendanceSession.findByIdAndUpdate(
          s._id,
          { status: s.status, qrToken: s.qrToken, lastRegeneratedAt: s.lastRegeneratedAt },
          { new: true }
        ).lean();
        if (updatedDoc) doc = updatedDoc;
      }

      updatedSessions.push({
        id: doc._id.toString(),
        subjectId: doc.subjectId,
        subjectName: doc.subjectName || '',
        teacherId: doc.teacherId,
        teacherName: doc.teacherName || '',
        generatedTime: doc.generatedTime,
        expiryTime: doc.expiryTime,
        status: doc.status,
        sessionCode: doc.sessionCode,
        qrToken: doc.qrToken,
        lastRegeneratedAt: doc.lastRegeneratedAt,
        createdAt: doc.createdAt ? doc.createdAt.toISOString() : new Date().toISOString()
      });
    }

    return updatedSessions;
  }

